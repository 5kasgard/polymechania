def roman_to_int(s: str) -> int:
    """
    Converts a Roman numeral string to an integer.
    Validates that the input is the unique canonical form for 1-3999.
    """
    if not s or not isinstance(s, str):
        raise ValueError("Invalid input")

    mapping = {
        'I': 1,
        'V': 5,
        'X': 10,
        'L': 50,
        'C': 100,
        'D': 500,
        'M': 1000
    }

    # Check for non-uppercase or invalid characters
    if not all(c in mapping for c in s):
        raise ValueError("Invalid characters or casing")

    # The canonical form for 1-3999 can be generated by a regex pattern.
    # M{0,3}        -> Thousands: 0 to 3000
    # (CM|CD|D?C{0,3}) -> Hundreds: 900, 400, or 500-800, or 0-300
    # (XC|XL|L?X{0,3}) -> Tens: 90, 40, or 50-80, or 0-30
    # (IX|IV|V?I{0,3}) -> Ones: 9, 4, or 5-8, or 0-3
    # We must ensure the string is not empty after matching.
    
    import re
    pattern = r'^M{0,3}(CM|CD|D?C{0,3})(XC|XL|L?X{0,3})(IX|IV|V?I{0,3})$'
    if not re.match(pattern, s) or s == "":
        raise ValueError("Not a canonical Roman numeral")

    total = 0
    prev_value = 0
    
    # Process from right to left to handle subtractive pairs easily
    for char in reversed(s):
        current_value = mapping[char]
        if current_value < prev_value:
            total -= current_value
        else:
            total += current_value
        prev_value = current_value

    # Final check for range 1-3999
    if not (1 <= total <= 3999):
        raise ValueError("Out of range")

    return total
