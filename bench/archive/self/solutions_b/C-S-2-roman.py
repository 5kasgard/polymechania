def roman_to_int(s: str) -> int:
    """
    Converts a Roman numeral string to an integer.
    Only accepts the unique canonical form for 1 to 3999.
    """
    if not s:
        raise ValueError("Empty string is not a valid Roman numeral.")

    mapping = {
        'I': 1,
        'V': 5,
        'X': 10,
        'L': 50,
        'C': 100,
        'D': 500,
        'M': 1000
    }

    # Check for invalid characters or lowercase
    if not all(c in mapping for c in s):
        raise ValueError("Invalid characters in Roman numeral.")

    # Build the value and check for subtractive pairs
    # We use a standard algorithm but must validate the canonical form.
    # The canonical form for 1-3999 can be generated by a rule-based approach.
    # A reliable way to validate "unique canonical form" is to convert the 
    # integer back to Roman and see if it matches the input.
    
    total = 0
    prev_val = 0
    for char in reversed(s):
        val = mapping[char]
        if val < prev_val:
            total -= val
        else:
            total += val
        prev_val = val

    if not (1 <= total <= 3999):
        raise ValueError("Roman numeral out of range 1-3999.")

    # Generate the canonical Roman numeral for the calculated total
    def int_to_roman_canonical(n: int) -> str:
        res = ""
        # Thousands
        res += "M" * (n // 1000)
        n %= 1000
        # Hundreds
        if n >= 900:
            res += "CM"
            n -= 900
        elif n >= 500:
            res += "D"
            n -= 500
        elif n >= 400:
            res += "CD"
            n -= 400
        res += "C" * (n // 100)
        n %= 100
        # Tens
        if n >= 90:
            res += "XC"
            n -= 90
        elif n >= 50:
            res += "L"
            n -= 50
        elif n >= 40:
            res += "XL"
            n -= 40
        res += "X" * (n // 10)
        n %= 10
        # Ones
        if n >= 9:
            res += "IX"
            n -= 9
        elif n >= 5:
            res += "V"
            n -= 5
        elif n >= 4:
            res += "IV"
            n -= 4
        res += "I" * n
        return res

    if int_to_roman_canonical(total) != s:
        raise ValueError("Not a unique canonical Roman numeral.")

    return total
